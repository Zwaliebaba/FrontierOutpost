#!/usr/bin/env python3
"""Fail the build on a C++ file that is not formatted to /.clang-format.

AGENTS.md 4 makes /.clang-format the authority for C++ layout. This script is what makes that
claim true rather than aspirational: it runs clang-format over every hand-written .cpp and .h in
the tree and exits non-zero if any file would change.

This tree is greenfield, so the check runs over the WHOLE tree rather than over a diff. A
whole-tree run must be a no-op; if it is not, the fix is to run clang-format, not to narrow the
check.

CLANG-FORMAT VERSION MATTERS. The output changes between releases -- 18 and 22 disagree about
where to break a long call -- so CI pins one version and this script prints the one it used and
warns when it is not the pinned one. If a local run disagrees with CI, compare the version line
before anything else.

Usage:
    python Build/CheckFormat.py                 # check, print a diff for each offender
    python Build/CheckFormat.py --fix           # rewrite the offenders in place
    python Build/CheckFormat.py --clang-format <path>
"""

from __future__ import annotations

import argparse
import difflib
import os
import re
import shutil
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The version CI installs. A different one is allowed but reported, because a green local run
# under another version says nothing about the gate.
PINNED_VERSION = "18.1.3"

SOURCE_SUFFIXES = (".cpp", ".h")

# Build output, IDE state and the vendored nothing-at-all. Anything under these never reaches
# clang-format.
# CompiledShaders holds build output: the headers the shader compiler writes (AGENTS.md 3). Never
# hand-written, never committed, never formatted or linted.
SKIP_DIRECTORIES = {".git", ".vs", "x64", "packages", "__pycache__", "CompiledShaders"}

# Files nobody hand-writes. Resource.h is regenerated by the Visual Studio resource editor from
# the .rc, and formatting it only guarantees a diff the next time someone opens the dialog editor.
GENERATED_FILES = {
    os.path.join("Lockstep", "Resource.h"),
}


def find_clang_format(explicit: str | None) -> str:
    for candidate in (explicit, os.environ.get("CLANG_FORMAT"), "clang-format"):
        if not candidate:
            continue
        resolved = shutil.which(candidate) or (candidate if os.path.isfile(candidate) else None)
        if resolved:
            return resolved
    sys.exit("CheckFormat: no clang-format found. Pass --clang-format <path> or set CLANG_FORMAT.")


def clang_format_version(binary: str) -> str:
    text = subprocess.run([binary, "--version"], capture_output=True, text=True, check=True).stdout
    match = re.search(r"(\d+\.\d+\.\d+)", text)
    return match.group(1) if match else text.strip()


def source_files() -> list[str]:
    found: list[str] = []
    for directory, subdirectories, files in os.walk(REPO_ROOT):
        subdirectories[:] = [d for d in subdirectories if d not in SKIP_DIRECTORIES]
        for name in files:
            if not name.endswith(SOURCE_SUFFIXES):
                continue
            relative = os.path.relpath(os.path.join(directory, name), REPO_ROOT)
            if relative in GENERATED_FILES:
                continue
            found.append(relative)
    return sorted(found)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--clang-format", dest="binary", default=None, help="clang-format to run")
    parser.add_argument("--fix", action="store_true", help="rewrite offending files instead of reporting them")
    arguments = parser.parse_args()

    binary = find_clang_format(arguments.binary)
    version = clang_format_version(binary)
    print(f"CheckFormat: {binary} ({version})")
    if version != PINNED_VERSION:
        print(f"CheckFormat: WARNING - CI pins clang-format {PINNED_VERSION}. Output can differ between releases.")

    files = source_files()
    if not files:
        sys.exit("CheckFormat: found no source files, which means the walk is wrong, not that the tree is clean.")

    offenders: list[str] = []
    for relative in files:
        absolute = os.path.join(REPO_ROOT, relative)
        with open(absolute, "r", encoding="utf-8-sig", newline="") as handle:
            original = handle.read().replace("\r\n", "\n")

        # Feed LF and nothing else. subprocess in text mode translates \n to \r\n on Windows when
        # it writes stdin, so passing a CRLF file through would arrive as \r\r\n and clang-format
        # would read every stray \r as a line of its own -- a diff on every line of every file,
        # with nothing actually wrong.
        formatted = subprocess.run(
            [binary, "--style=file", f"-assume-filename={absolute}"],
            input=original,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.replace("\r\n", "\n")

        # Both sides are LF here. .clang-format leaves LineEnding at its default on purpose so the
        # same command is a no-op on a CRLF working tree and in a LF container; .editorconfig, not
        # this check, is what settles which one lands on disk.
        if original == formatted:
            continue

        offenders.append(relative)
        if arguments.fix:
            with open(absolute, "w", encoding="utf-8", newline="\r\n") as handle:
                handle.write(formatted)
            continue

        diff = difflib.unified_diff(
            original.splitlines(keepends=True),
            formatted.splitlines(keepends=True),
            fromfile=f"{relative} (on disk)",
            tofile=f"{relative} (clang-format)",
        )
        sys.stdout.writelines(diff)

    print(f"CheckFormat: checked {len(files)} files, {len(offenders)} unformatted")
    if not offenders:
        return 0
    if arguments.fix:
        for relative in offenders:
            print(f"  reformatted {relative}")
        return 0
    for relative in offenders:
        print(f"  {relative}")
    print("CheckFormat: run `python Build/CheckFormat.py --fix` and commit the result.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
